export function getDestinationBySlug(slug) {
  let normalizedSlug = String(slug ?? '')
    .toLowerCase()
    .replace(/^\/+|\/+$/g, '')
    .trim()
  const aliased = STATIC_DESTINATION_SLUG_ALIASES[normalizedSlug]
  if (aliased) normalizedSlug = String(aliased).toLowerCase()
  const found = destinations.find(
    (d) =>
      getDestinationSlug(d) === normalizedSlug ||
      String(d.id).toLowerCase() === normalizedSlug
  )
  return found ?? createVirtualDestination(normalizedSlug)
}

export function getDestinationById(id) {
  return destinations.find((d) => d.id === id)
}
